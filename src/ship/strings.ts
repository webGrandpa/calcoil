const DICTS: Record<Lang, Dict> = { ka, ru, en };
export type SKey = keyof Dict;

export function makeST(lang: Lang) {
  const d = DICTS[lang];
  return (key: SKey, params: Record<string, string | number> = {}): string =>
    d[key].replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

export type ST = ReturnType<typeof makeST>;
export const noteText = (st: ST, n: ShipNote) => st(`n_${n.code}` as SKey, n.params ?? {});
