const DICTS: Record<Lang, Dict> = { ka, ru, en };

export type AKey = keyof Dict;

export function makeAT(lang: Lang) {
  const d = DICTS[lang];
  return (key: AKey, params: Record<string, string | number> = {}): string =>
    (d[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

export type AT = ReturnType<typeof makeAT>;
